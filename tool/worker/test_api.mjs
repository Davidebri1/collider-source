// Exercises every call account_sync_client.dart makes, against BASE
// (default: local `npm run dev`). Needs DEV_AUTH=1 on that Worker.
const BASE = (process.env.BASE || 'http://127.0.0.1:9300').replace(/\/$/, '');
const O = { Origin: 'https://davidebri1.github.io' };
let pass = 0, fail = 0;
const ok = (name, cond, d = '') => { cond ? pass++ : fail++; console.log(`${cond ? 'PASS' : 'FAIL'}  ${name}${d ? '  ' + d : ''}`); };
const j = (r) => r.json();
let r = await fetch(`${BASE}/health`, { headers: O });
ok('GET /health 200', r.status === 200);
ok('CORS allows the Pages origin', r.headers.get('access-control-allow-origin') === O.Origin);
r = await fetch(`${BASE}/health`, { method: 'OPTIONS', headers: { Origin: 'https://evil.example' } });
ok('OPTIONS from another origin 403', r.status === 403);
r = await fetch(`${BASE}/auth/google`, { method: 'POST', headers: { ...O, 'Content-Type': 'application/json' }, body: JSON.stringify({ id_token: 'a.b.c' }) });
ok('POST /auth/google rejects a bad token', r.status === 401 || r.status === 503, `status ${r.status}`);
r = await fetch(`${BASE}/auth/dev`, { method: 'POST', headers: { ...O, 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'e2e@example.com', name: 'E2E' }) });
const s = await j(r);
ok('POST /auth/dev session shape', r.status === 200 && typeof s.accessToken === 'string' && typeof s.userId === 'string' && !isNaN(Date.parse(s.expiresAt)));
const A = { ...O, Authorization: `Bearer ${s.accessToken}`, 'Content-Type': 'application/json' };
r = await fetch(`${BASE}/auth/me`, { headers: A }); const me = await j(r);
ok('GET /auth/me', r.status === 200 && me.userId === s.userId && me.email === 'e2e@example.com');
r = await fetch(`${BASE}/v1/records`, { headers: { ...O } });
ok('records need auth (401)', r.status === 401);
r = await fetch(`${BASE}/v1/records/${encodeURIComponent('smartgen')}/${encodeURIComponent('board 1')}`, { method: 'PUT', headers: A, body: JSON.stringify({ collection: 'smartgen', id: 'board 1', data: { name: 'Board' }, updatedAtMs: 1000, deleted: false }) });
ok('PUT record', r.status === 200);
r = await fetch(`${BASE}/v1/records/smartgen/board%201`, { method: 'PUT', headers: A, body: JSON.stringify({ collection: 'smartgen', id: 'board 1', data: { name: 'Older' }, updatedAtMs: 500 }) });
ok('older PUT is skipped (last writer wins)', (await j(r)).skipped === true);
r = await fetch(`${BASE}/v1/records?since=0`, { headers: A }); let items = (await j(r)).items;
ok('GET records since 0', items.length === 1 && items[0].data.name === 'Board' && items[0].updatedAtMs === 1000);
r = await fetch(`${BASE}/v1/records?since=1000`, { headers: A }); items = (await j(r)).items;
ok('GET records since 1000 is empty', items.length === 0);
r = await fetch(`${BASE}/v1/records/smartgen/board%201?updatedAtMs=2000`, { method: 'DELETE', headers: A });
ok('DELETE record 204', r.status === 204);
r = await fetch(`${BASE}/v1/records?since=1500`, { headers: A }); items = (await j(r)).items;
ok('deleted record comes back as a tombstone', items.length === 1 && items[0].deleted === true);
const bytes = new Uint8Array(300000).map((_, i) => i % 251);
r = await fetch(`${BASE}/v1/blobs/${encodeURIComponent('file/a b.png')}`, { method: 'PUT', headers: { ...O, Authorization: A.Authorization, 'Content-Type': 'application/octet-stream', 'X-Updated-At': '3000' }, body: bytes });
ok('PUT blob', r.status === 200);
r = await fetch(`${BASE}/v1/blobs/${encodeURIComponent('file/a b.png')}`, { headers: { ...O, Authorization: A.Authorization } });
const got = new Uint8Array(await r.arrayBuffer());
ok('GET blob returns the same bytes', r.status === 200 && got.length === bytes.length && got.every((v, i) => v === bytes[i]));
r = await fetch(`${BASE}/v1/blobs?since=0`, { headers: A }); items = (await j(r)).items;
ok('GET blob meta', items.length === 1 && items[0].id === 'file/a b.png' && items[0].sizeBytes === bytes.length && items[0].updatedAtMs === 3000);
r = await fetch(`${BASE}/v1/blobs/${encodeURIComponent('file/a b.png')}`, { method: 'DELETE', headers: A });
ok('DELETE blob 204', r.status === 204);
r = await fetch(`${BASE}/v1/blobs/${encodeURIComponent('file/a b.png')}`, { headers: A });
ok('deleted blob 404', r.status === 404);
r = await fetch(`${BASE}/auth/signout`, { method: 'POST', headers: A });
ok('POST /auth/signout 204', r.status === 204);
r = await fetch(`${BASE}/auth/me`, { headers: A });
ok('token is dead after sign-out', r.status === 401);
console.log(`\n${pass}/${pass + fail} passed`);
process.exit(fail ? 1 : 0);
